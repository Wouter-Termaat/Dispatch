-- Dispatch: database-schema + startdata
-- Plak dit hele script in Supabase > SQL Editor > New query en klik Run. Je kunt het veilig opnieuw draaien.

create table if not exists public.coasters (
  id text primary key,
  name text not null,
  park text not null,
  manufacturer text,
  operational boolean not null default true,
  photo_url text,
  created_by uuid,
  created_at timestamptz not null default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  key text unique not null,
  name text not null,
  dynamics jsonb,
  settings jsonb not null default '{}'::jsonb
);

create table if not exists public.entries (
  user_id uuid not null references public.profiles(id) on delete cascade,
  coaster_id text not null references public.coasters(id) on update cascade on delete cascade,
  initial_rank real not null,
  prior_strength real not null default 1,
  reridden_at timestamptz,
  note text,
  added_at timestamptz not null default now(),
  primary key (user_id, coaster_id)
);

create table if not exists public.comparisons (
  id bigint generated always as identity primary key,
  user_id uuid not null default auth.uid() references public.profiles(id) on delete cascade,
  batch uuid not null,
  a text not null references public.coasters(id) on update cascade on delete cascade,
  b text not null references public.coasters(id) on update cascade on delete cascade,
  outcome text not null check (outcome in ('a','b','tie','skip')),
  mode text,
  created_at timestamptz not null default now()
);
create index if not exists comparisons_user_idx on public.comparisons(user_id, created_at);

alter table public.coasters enable row level security;
alter table public.profiles enable row level security;
alter table public.entries enable row level security;
alter table public.comparisons enable row level security;

grant usage on schema public to authenticated;
grant select, insert, update, delete on public.coasters, public.profiles, public.entries, public.comparisons to authenticated;
revoke all on public.coasters, public.profiles, public.entries, public.comparisons from anon;

-- Iedereen die is ingelogd mag alles lezen (jullie zien elkaars lijst)
drop policy if exists "read coasters" on public.coasters;
create policy "read coasters" on public.coasters for select to authenticated using (true);
drop policy if exists "add coasters" on public.coasters;
create policy "add coasters" on public.coasters for insert to authenticated with check (true);
drop policy if exists "edit coasters" on public.coasters;
create policy "edit coasters" on public.coasters for update to authenticated using (true) with check (true);

drop policy if exists "read profiles" on public.profiles;
create policy "read profiles" on public.profiles for select to authenticated using (true);
drop policy if exists "edit own profile" on public.profiles;
create policy "edit own profile" on public.profiles for update to authenticated using (id = auth.uid()) with check (id = auth.uid());

-- Alleen je eigen lijst en duels bewerken
drop policy if exists "read entries" on public.entries;
create policy "read entries" on public.entries for select to authenticated using (true);
drop policy if exists "own entries insert" on public.entries;
create policy "own entries insert" on public.entries for insert to authenticated with check (user_id = auth.uid());
drop policy if exists "own entries update" on public.entries;
create policy "own entries update" on public.entries for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
drop policy if exists "own entries delete" on public.entries;
create policy "own entries delete" on public.entries for delete to authenticated using (user_id = auth.uid());

drop policy if exists "read comparisons" on public.comparisons;
create policy "read comparisons" on public.comparisons for select to authenticated using (true);
drop policy if exists "own comparisons insert" on public.comparisons;
create policy "own comparisons insert" on public.comparisons for insert to authenticated with check (user_id = auth.uid());
drop policy if exists "own comparisons delete" on public.comparisons;
create policy "own comparisons delete" on public.comparisons for delete to authenticated using (user_id = auth.uid());

